import { test, expect } from "@playwright/test";

test("calibration follows slope/rise/custom modes and exports/imports only the dev scene", async ({ page }) => {
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto("/__dev/paragon/calibration");
  await expect(page.getByRole("heading", { name: "Paragon Calibration" })).toBeVisible();
  await expect(page.locator("canvas")).toBeVisible();
  await expect(page.getByTestId("rake")).toHaveText("22.50°");
  await expect(page.getByTestId("side-clearance")).toHaveText("3.00 / 3.00 ม.");
  await expect(page.locator(".calibration-table tbody tr")).toHaveCount(13);
  await expect(page.locator(".calibration-table tbody tr").first()).toContainText("5.340");
  await page.getByLabel("ระยะแถวแนวราบ", { exact: false }).fill("1.3");
  await expect(page.getByTestId("rake")).toHaveText("22.50°");
  await page.getByLabel("โหมดปรับระดับพื้น").selectOption("rise");
  await page.getByLabel("ความสูงต่างแถวปกติ", { exact: false }).fill("0.4");
  await expect(page.getByTestId("rake")).toHaveText("17.10°");
  await page.getByLabel("โหมดปรับระดับพื้น").selectOption("custom");
  await page.getByRole("spinbutton", { name: "ระดับแถว K", exact: true }).fill("0.2");
  await expect(page.getByRole("alert")).toContainText("เพิ่มขึ้นไปด้านหลัง");
  await expect(page.getByRole("button", { name: "ดาวน์โหลด JSON" })).toBeDisabled();
  await page.getByRole("spinbutton", { name: "ระดับแถว K", exact: true }).fill("0.7");
  await expect(page.getByRole("alert")).toHaveCount(0);
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "ดาวน์โหลด JSON" }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toBe("paragon-calibration-v1.json");
  await page.getByRole("button", { name: "คืนค่าเริ่มต้น" }).click();
  await expect(page.getByTestId("rake")).toHaveText("22.50°");
  await page.getByLabel("นำเข้า Calibration JSON").setInputFiles(await download.path());
  await expect(page.getByLabel("โหมดปรับระดับพื้น")).toHaveValue("custom");
  await expect(page.getByRole("spinbutton", { name: "ระดับแถว K", exact: true })).toHaveValue("0.7");
  await page.getByLabel("นำเข้า Calibration JSON").setInputFiles({ name: "invalid.json", mimeType: "application/json", buffer: Buffer.from('{"version":2}') });
  await expect(page.getByRole("status").first()).toContainText("นำเข้าไม่ได้");
  await expect(page.getByRole("spinbutton", { name: "ระดับแถว K", exact: true })).toHaveValue("0.7");
  await page.goto("/__dev/paragon/calibration");
  await expect(page.getByTestId("rake")).toHaveText("22.50°");
  expect(errors).toEqual([]);
});

test("calibration camera views respond to eye changes and fit desktop/mobile layouts", async ({ page }) => {
  test.setTimeout(60000);
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto("/__dev/paragon/calibration");
  await expect(page.locator("canvas")).toBeVisible();
  await page.getByRole("button", { name: "หยุดวิดีโอ" }).click();
  await page.screenshot({ path: "output/playwright/calibration-side.png", fullPage: true });
  await page.getByRole("button", { name: "ด้านบน", exact: true }).click();
  await page.screenshot({ path: "output/playwright/calibration-top.png", fullPage: true });
  await page.getByRole("button", { name: "จากที่นั่ง", exact: true }).click();
  const previous = await page.locator(".calibration-canvas").getAttribute("data-eye-position");
  await page.getByLabel("ความสูงสายตาเหนือพื้น", { exact: false }).fill("1.3");
  await expect(page.locator(".calibration-canvas")).not.toHaveAttribute("data-eye-position", previous);
  const combo = page.getByRole("combobox", { name: "เลือกที่นั่งเพื่อดูมุมมอง" });
  await combo.fill("l4"); await page.keyboard.press("Enter");
  await expect(combo).toHaveValue("L4");
  await page.getByRole("button", { name: "หันกลับหาจอ" }).click();
  await page.screenshot({ path: "output/playwright/calibration-seat.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "ด้านข้าง", exact: true }).click();
  await page.screenshot({ path: "output/playwright/calibration-mobile.png", fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
